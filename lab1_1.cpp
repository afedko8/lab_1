#include<iostream>
#include<vector>

// Структура для хранения точки на плоскости.
// Координаты — long double для большей точности вычислений.
struct Point {
    long double x, y;
    Point(long double x_val, long double y_val) : x(x_val), y(y_val) {}
};

// Возвращает знак числа: -1, 0 или 1.
// Сравнение с эпсилон (1e-12) вместо == 0 нужно, чтобы избежать
// ошибок из-за погрешности вычислений с плавающей точкой.
int sign(long double x){
    if (std::abs(x)<1e-12) return 0;
    return x<0 ? -1:1;
}

// Проверяет, лежат ли точки c и m по одну сторону от прямой,
// проходящей через точки a и b (либо m лежит прямо на прямой).
// Используется для проверки принадлежности точки треугольнику:
// если точка p лежит по ту же сторону от каждой стороны треугольника,
// что и противоположная вершина — точка внутри треугольника.
int valid(Point &a, Point &b, Point &c, Point &m) {
    long double deltaC, deltaM; // отклонения точек c и m от прямой ab

    if (a.x == b.x) {
        // Прямая ab вертикальная (x = const) — уравнение прямой
        // через угловой коэффициент K не годится (деление на 0),
        // поэтому сравниваем напрямую по координате x.
        deltaC = c.x - a.x;
        deltaM = m.x - a.x;
    } else {
        // Обычный случай: строим прямую вида y = K*x + B
        // через точки a и b.
        long double K = (a.y - b.y) / (a.x - b.x); // угловой коэффициент
        long double B = a.y - K * a.x;              // свободный член

        // Отклонение точки от прямой — разница между её фактической
        // координатой y и той, что даёт уравнение прямой при этом x.
        // Знак отклонения показывает, с какой стороны от прямой лежит точка.
        deltaC = c.y - (c.x * K + B);
        deltaM = m.y - (m.x * K + B);
    }

    // Если c и m лежат по одну сторону от прямой (одинаковый знак),
    // либо m лежит точно на прямой (deltaM == 0) — точка m допустима
    // относительно этой стороны треугольника.
    if (sign(deltaC) == sign(deltaM) || sign(deltaM) == 0)
        return 1;
    return 0;
}

// Проверяет, лежит ли точка p внутри треугольника triangle.
// Точка внутри треугольника тогда и только тогда, когда для каждой
// из трёх сторон точка p лежит с той же стороны, что и противоположная
// этой стороне вершина треугольника.
bool in_triangle(std::vector<Point> triangle, Point p){
        if (valid(triangle[0],triangle[1], triangle[2], p) &&   // сторона (0,1), проверяем относительно вершины 2
            valid(triangle[1],triangle[2], triangle[0], p) &&   // сторона (1,2), проверяем относительно вершины 0
            valid(triangle[2],triangle[0], triangle[1], p)){    // сторона (2,0), проверяем относительно вершины 1
             std::cout<<"YES"<<std::endl;
            return 1;
        } else{
             std::cout<<"NO"<< std::endl;
            return 0;
        }
}

int main(){
    long double x,y;

    // Треугольник хранится как вектор из 3 вершин (изначально нулевые).
    std::vector<Point> tr = {Point(0,0), Point(0,0), Point(0,0)};

    // Ввод координат треугольника (предполагается корректный ввод,
    // т.е. заранее известно, что три точки действительно образуют треугольник).
    for (size_t i = 0; i < 3; i++)
    {
        std::cin>>tr[i].x >> tr[i].y;
    }
    
    // Считываем точки для проверки, пока не встретим пару (0, 0) —
    // это признак конца ввода.
    for (;std::cin>>x>>y && !(x == 0 && y ==0);)
    {
        // Для каждой введённой точки выводим YES/NO —
        // находится ли она внутри треугольника tr.
        in_triangle(tr,Point(x,y));
    }
}
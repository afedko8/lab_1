#include<iostream>

int main(){
    // cnt — количество введённых чисел (без учёта завершающего нуля)
    // cnt5 — количество положительных чисел, кратных 5
    // cnt2 — количество чисел, являющихся степенью двойки
    // tmp1, tmp2 — два предыдущих числа (для проверки в пункте д)
    // cntd — количество чисел, превышающих сумму двух предыдущих
    int x,cnt=0,cnt5=0, cnt2=0,tmp1,tmp2,cntd=0;
    std::cin>>x;

    // Инициализируем min/max первым введённым числом,
    // sum — сумма всех чисел (для среднего арифметического)
    int max=x, min =x, sum = 0;

    // Читаем числа, пока не встретим 0 — признак конца последовательности
    while(x != 0){
        cnt++;

        // Обновляем минимум и максимум
        if (x<min) min = x;
        if (x>max) max = x;

        sum+=x;

        // Пункт в): положительное и кратное 5
        if (x>0 && x%5==0) cnt5++;

        // Пункт г): проверка на степень двойки битовым трюком.
        // У степени двойки в двоичном представлении ровно один
        // установленный бит, поэтому x & (x-1) обнуляет этот бит
        // и результат равен 0. Условие x>0 нужно, чтобы не считать
        // отрицательные числа и не словить неопределённое поведение
        // при x=0 (для x=0 x-1 даёт -1, и x&(x-1) тоже 0, что было
        // бы ложным срабатыванием).
        if (x > 0 && (x & (x-1))==0) cnt2++;

        // Пункт д): сравнение текущего числа с суммой двух
        // предшествующих ему элементов последовательности.
        if (cnt<3)
        {   
            // Первые два числа последовательности просто запоминаем —
            // сравнивать их не с чем, предшественников ещё нет.
            if (cnt == 1)
            {
                tmp1 = x;
            } else{
                tmp2 = x;
            }
            
        } else{
            // Начиная с третьего числа сравниваем его с суммой
            // двух предыдущих сохранённых чисел
            if (tmp1+tmp2<x) cntd++;

            // Сдвигаем окно из двух последних чисел на одну позицию:
            // tmp1 теперь — предпоследнее, tmp2 — текущее число
            tmp1 = tmp2;
            tmp2 = x; 
        }
        std::cin>>x;
    }

    // Пункт а): среднее арифметическое.
    // Приводим sum к double, чтобы получить точный (не целочисленный)
    // результат деления. Проверка cnt != 0 защищает от деления на 0,
    // если сразу был введён 0 (пустая последовательность).
    double ans = 0.0;
    if (cnt != 0) ans = static_cast<double>(sum)/cnt;
    
    // Выводим все пять результатов:
    // а) среднее арифметическое
    // б) разница максимума и минимума
    // в) количество положительных чисел, кратных 5
    // г) количество чисел — степеней двойки
    // д) количество чисел, превышающих сумму двух предыдущих
    printf("a) %lf b) %d c) %d d) %d e) %d ", ans, max-min, cnt5, cnt2, cntd);
    return 0;
}